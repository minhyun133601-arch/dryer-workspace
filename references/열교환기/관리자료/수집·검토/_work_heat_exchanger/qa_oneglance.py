from pathlib import Path
from evidence_paths import EVIDENCE_ROOT, FINAL_DIR
import json,re,hashlib
from playwright.sync_api import sync_playwright
ROOT=EVIDENCE_ROOT
WORK=Path(__file__).resolve().parent
OUT=FINAL_DIR/'열교환기 한눈에.html'
checks=[]
def check(name,ok,detail=''):
    assert ok,(name,detail)
    checks.append({'name':name,'passed':True,'detail':detail})
with sync_playwright() as pw:
    b=pw.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
    c=b.new_context(accept_downloads=True,viewport={'width':1440,'height':900})
    p=c.new_page();errors=[];requests=[]
    p.on('pageerror',lambda e:errors.append(str(e)))
    p.on('request',lambda r:requests.append(r.url) if r.url.startswith(('http://','https://')) else None)
    p.goto(OUT.as_uri(),wait_until='load')
    val=lambda id:p.locator('#'+id).inner_text()
    def fill(id,v):p.locator('#'+id).fill(str(v))
    check('baseline gas',val('gas-output')=='21.45',val('gas-output'))
    check('baseline annual',val('annual-exact').startswith('277,992,000'),val('annual-exact'))
    check('baseline payback',val('payback-output')=='2.60',val('payback-output'))
    check('baseline unknown net',val('net-output')=='미산정')
    fill('tout-number',50)
    check('50 degree gas',val('gas-output')=='16.5')
    check('50 degree annual',val('annual-exact').startswith('213,840,000'))
    check('50 degree payback',val('payback-output')=='3.39')
    p.locator('[data-temp="62"]').click()
    check('62 degree annual',val('annual-exact').startswith('299,376,000'))
    check('62 degree payback',val('payback-output')=='2.42')
    check('range input sync',p.locator('#tout-range').input_value()=='62')
    p.locator('#reset').click();fill('tin-number',35)
    check('warm inlet annual',val('annual-exact').startswith('171,072,000'))
    check('warm inlet payback',val('payback-output')=='4.23')
    fill('tout-number',20)
    check('no positive rise gas zero',val('gas-output')=='0')
    check('no heat no payback',val('payback-output')=='산정불가')
    p.locator('#reset').click();fill('days',0)
    check('zero operation no payback',val('payback-output')=='산정불가')
    fill('days',366)
    check('invalid day',not p.locator('#input-error').is_hidden())
    p.locator('#reset').click();fill('gas-price',-1)
    check('negative price rejected',not p.locator('#input-error').is_hidden())
    p.locator('#reset').click()
    p.locator('#advanced-open').click();fill('delta-kw',50);fill('electricity-price',150);fill('maintenance',500)
    check('net scenario',val('net-output')=='21,899.2만원/년',val('net-output'))
    check('net payback',val('net-payback')=='3.31년')
    fill('delta-kw','')
    check('blank not zero',val('net-output')=='미산정')
    p.keyboard.press('Escape');p.locator('#reset').click()
    p.locator('[data-drawing="front"]').click()
    check('drawing changes','정면도' in p.locator('#drawing-image').get_attribute('alt'))
    p.locator('#expand').click();check('image dialog opens',p.locator('#image-dialog').evaluate('(e)=>e.open'))
    p.keyboard.press('Escape');check('image dialog closes',not p.locator('#image-dialog').evaluate('(e)=>e.open'))
    p.locator('[data-drawing="install"]').click()
    p.screenshot(path=str(WORK/'oneglance-desktop.png'),full_page=True)
    check('desktop viewport core',p.locator('.results').bounding_box()['y']+p.locator('.results').bounding_box()['height']<=900)
    p.set_viewport_size({'width':1366,'height':768})
    p.screenshot(path=str(WORK/'oneglance-compact.png'),full_page=True)
    check('compact core visible',p.locator('.results').bounding_box()['y']+p.locator('.results').bounding_box()['height']<=768,str(p.locator('.results').bounding_box()))
    p.set_viewport_size({'width':390,'height':844})
    check('mobile no overflow',p.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    p.screenshot(path=str(WORK/'oneglance-mobile.png'),full_page=True)
    p.locator('#evidence-open').click()
    receipt=json.loads((WORK/'oneglance_receipt.json').read_text('utf8'))
    for f in receipt['files']:
        with p.expect_download() as dl:
            p.locator('[data-file="'+f['id']+'"]').click()
        item=dl.value;raw=Path(item.path()).read_bytes()
        check('original '+f['name'],hashlib.sha256(raw).hexdigest()==f['sha256'])
    check('no errors',not errors,str(errors));check('no network',not requests,str(requests))
    b.close()
(WORK/'oneglance_qa.json').write_text(json.dumps({'output':str(OUT),'checks':checks},ensure_ascii=False,indent=2),encoding='utf8')
print('PASSED',len(checks))
